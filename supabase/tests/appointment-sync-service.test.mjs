import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const repo = readFileSync('supabase/appointment-repository.js','utf8');
const service = readFileSync('supabase/appointment-sync-service.js','utf8');
const schema = readFileSync('supabase/002_operational_tables.sql','utf8');
const overlap = readFileSync('supabase/007_stock_privileges_and_appointment_overlap.sql','utf8');
const identity = readFileSync('supabase/016_appointment_local_identity.sql','utf8');
for (const fn of ['listRemoteAppointments','listRemoteAppointmentEvents','createRemoteAppointment','updateRemoteAppointment','upsertRemoteAppointmentFromLocal']) {
  assert.ok(repo.includes('export async function '+fn), 'repository exports '+fn);
}
assert.ok(repo.includes(".eq('clinic_id', clinicId).eq('branch_id', branchId)"), 'appointment operations must be clinic and branch scoped');
assert.ok(repo.includes(".eq('updated_at', expectedUpdatedAt)"), 'updates must use optimistic concurrency');
assert.ok(repo.includes('source_local_id: stableLocalId'), 'local identity must be stable and explicit');
assert.ok(repo.includes('Mapped remote dentist user ID'), 'local dentist IDs must never be mistaken for Auth IDs');
assert.ok(repo.includes('Mapped remote chair ID'), 'local chair IDs must never be mistaken for remote IDs');
assert.ok(repo.includes('created_by: userId'), 'creator must come from authenticated session');
assert.ok(repo.includes("new Set(['scheduled','confirmed','arrived','completed','cancelled','no_show'])"), 'status values must be allowlisted');
assert.ok(repo.includes('Appointment end must be after its start.'), 'end must follow start');
assert.ok(service.includes('requireActiveClinicContext(await getCurrentClinicMembership())'));
assert.ok(service.includes('requireAssignedRemoteBranch(context, branchId, branches.map(branch => branch.id))'));
assert.ok(service.includes("new Set(['owner','manager','dentist','reception'])"));
assert.ok(service.includes('upsertAppointmentInAssignedBranch'), 'safe idempotent upsert is exposed');
assert.ok(service.includes('listAppointmentEventsForAssignedBranch'), 'event history is branch-scoped');
assert.ok(identity.includes('record_clinic_appointment_event'), 'remote appointment changes append immutable event history');
assert.ok(schema.includes("check (status in ('scheduled','confirmed','arrived','completed','cancelled','no_show'))"));
assert.ok(overlap.includes('prevent_dentist_appointment_overlap'), 'database must enforce dentist overlap');
assert.ok(overlap.includes('pg_advisory_xact_lock'), 'overlap prevention must serialize concurrent writes');
assert.ok(identity.includes('clinic_appointments_local_identity_uidx'), 'stable local identity must be unique within a branch');
assert.ok(identity.includes('enforce_appointment_chair_branch'), 'chair must belong to appointment branch');
assert.ok(identity.includes('touch_appointment_updated_at'), 'appointment version must advance on every update');
assert.doesNotMatch(repo+service,/localStorage|dcos1|service_role|secret key/i);
console.log('Appointment sync safety checks passed.');
