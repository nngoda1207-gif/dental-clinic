import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const repo = readFileSync('supabase/appointment-repository.js','utf8');
const service = readFileSync('supabase/appointment-sync-service.js','utf8');
const schema = readFileSync('supabase/002_operational_tables.sql','utf8');
const overlap = readFileSync('supabase/007_stock_privileges_and_appointment_overlap.sql','utf8');
for (const fn of ['listRemoteAppointments','createRemoteAppointment','updateRemoteAppointment']) assert.ok(repo.includes('export async function '+fn));
assert.ok(repo.includes(".eq('clinic_id', clinicId).eq('branch_id', branchId)"), 'all appointment operations must be clinic and branch scoped');
assert.ok(repo.includes('created_by: userId'), 'creator must come from authenticated session');
assert.ok(repo.includes("new Set") === false, 'no arbitrary dynamic status list is accepted');
assert.ok(repo.includes("new Set(['scheduled','confirmed','arrived','completed','cancelled','no_show'])"), 'status values must be allowlisted');
assert.ok(repo.includes('Appointment end must be after its start.'), 'end must follow start');
assert.ok(service.includes('requireActiveClinicContext(await getCurrentClinicMembership())'));
assert.ok(service.includes('requireAssignedRemoteBranch(context, branchId, branches.map(branch => branch.id))'));
assert.ok(service.includes("new Set(['owner','manager','dentist','reception'])"));
assert.ok(schema.includes("check (status in ('scheduled','confirmed','arrived','completed','cancelled','no_show'))"));
assert.ok(overlap.includes('prevent_dentist_appointment_overlap'), 'database must enforce dentist overlap');
assert.ok(overlap.includes('pg_advisory_xact_lock'), 'overlap prevention must serialize concurrent writes');
assert.doesNotMatch(repo+service,/localStorage|dcos1|service_role|secret key/i);
console.log('Appointment sync safety checks passed.');
