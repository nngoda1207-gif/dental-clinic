import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const repo=readFileSync('supabase/inventory-repository.js','utf8');
const service=readFileSync('supabase/inventory-sync-service.js','utf8');
const migration=readFileSync('supabase/017_inventory_idempotent_posting.sql','utf8');
assert.ok(repo.includes('upsertRemoteInventoryItemFromLocal'));
assert.ok(repo.includes('postRemoteInventoryMovementFromLocal'));
assert.ok(repo.includes('getRemoteInventoryItem'));
assert.ok(repo.includes("p_source_local_id:sourceId"),'every stock movement retry needs a stable local ID');
assert.ok(repo.includes("quantity:0,...payload"),'new item metadata must not overwrite or invent stock quantity');
assert.ok(repo.includes("eq('updated_at',expectedUpdatedAt)"),'item metadata updates use optimistic concurrency');
assert.ok(repo.includes("uuid(item.supplier_id,'Mapped remote supplier ID')"),'supplier IDs must be explicitly mapped');
assert.ok(service.includes('requireActiveClinicContext(await getCurrentClinicMembership())'));
assert.ok(service.includes('requireAssignedRemoteBranch(context,branchId,branches.map(x=>x.id))'));
assert.ok(service.includes('getRemoteInventoryItem({clinicId:s.clinicId,branchId:s.branchId,itemId:options.itemId})'));
assert.ok(migration.includes('clinic_inventory_movements_local_identity_uidx'));
assert.ok(migration.includes('for update'),'stock item must be locked before replay check');
assert.ok(migration.includes('post_inventory_movement_idempotent'));
assert.ok(migration.includes("using errcode = '23505'"),'reusing an ID with a different payload must be rejected');
assert.ok(migration.includes('touch_inventory_item_updated_at'));
assert.doesNotMatch(repo+service,/localStorage|dcos1|service_role|secret key/i);
console.log('Inventory sync safety checks passed.');
